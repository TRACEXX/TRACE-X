"""
TRACE AI - the investigation assistant.

Workflow for every question (see answer_question):
  1. The route has already checked the session.
  2. detect_intent() decides what kind of question it is.
  3. The case / detective / suspect named in the question is identified.
  4. Records are read from SQLite through fixed functions, limited to the
     cases this user may access (accessible_case_ids).
  5. DSA helpers do the work: merge sort for the timeline, the hash table
     for evidence lookups, linked-list custody chains.
  6. A deterministic answer is ALWAYS built from those records, so TRACE AI
     works with no LLM at all.
  7. If an LLM is configured, it receives only that authorised context and
     writes an explanation, which the UI labels as AI-generated.

TRACE AI never writes to case records. The only side effect is that
"generate a report" creates a PDF file, the same as the Reports button.
"""

from flask import url_for

from ai.context_builder import (SYSTEM_PROMPT, build_llm_prompt, deterministic_summary, detect_intent,
                                find_detective, find_suspects, llm_case_context, parse_case_numbers)
from ai.providers import AIProviderError, generate, provider_status
from database.db import log_activity
from database.queries import (case_bundle, cases_for_user_with_role, evidence_for_cases,
                              get_case_by_number, list_cases, suspect_code, suspect_linked_evidence)
from routes.auth import accessible_case_ids, is_admin

LLM_INTENTS = {"show_case", "summary", "timeline", "evidence", "suspect_evidence", "witnesses", "suspects", "search"}


def section(heading, items, kind="facts"):
    return {"heading": heading, "items": [str(i) for i in items], "kind": kind}


def answer_question(user, question, page_case=None):
    question = (question or "").strip()[:1000]
    allowed = accessible_case_ids(user)
    intent = detect_intent(question)
    case_numbers = parse_case_numbers(question) or ([page_case] if page_case else [])

    handler = HANDLERS[intent]
    result = handler(user, question, allowed, case_numbers)
    result.setdefault("references", [])
    result["intent"] = intent

    # Optional LLM explanation, built only from the authorised context.
    status = provider_status()
    result["ai"] = {"status": "disabled", "provider": status["name"], "message": status["message"], "text": None}
    if intent in LLM_INTENTS and result.get("context") and status["configured"]:
        try:
            result["ai"]["text"] = generate(SYSTEM_PROMPT, build_llm_prompt(question, result["context"]))
            result["ai"]["status"] = "ok"
            result["ai"]["message"] = f"Interpretation generated by {status['name']} ({status.get('model')})."
        except AIProviderError as error:
            result["ai"]["status"] = "unavailable"
            result["ai"]["message"] = f"AI provider unavailable: {error} Showing stored records only."
    result.pop("context", None)

    log_activity(user["id"], "TRACE AI query", "ai", ",".join(case_numbers) or None,
                 f"intent={intent}; question={question[:120]}")
    return result


# ---------------------------------------------------------------- helpers

def _resolve_case(case_numbers, allowed):
    """Return (bundle, error_message). Same message for 'missing' and 'forbidden'."""
    if not case_numbers:
        return None, "Which case? Include a case number, for example: \"Summarize Case 001\"."
    case = get_case_by_number(case_numbers[0])
    if case is None or case["id"] not in allowed:
        return None, f"{case_numbers[0]} does not exist or is not shared with you."
    return case_bundle(case["id"]), None


def _case_ref(case):
    return {"label": f"Open {case['case_number']}", "url": url_for("cases.view_case", case_number=case["case_number"])}


def _need_case(case_numbers, allowed):
    bundle, error = _resolve_case(case_numbers, allowed)
    if error:
        return None, {"sections": [section("Case needed", [error], "notice")]}
    return bundle, None


# --------------------------------------------------------------- handlers

def handle_show_case(user, question, allowed, case_numbers):
    bundle, error = _need_case(case_numbers, allowed)
    if error:
        return error
    c = bundle["case"]
    return {
        "sections": [
            section(f"{c['case_number']}: {c['title']}", [
                f"Category: {c['category']}", f"Status: {c['status']}",
                f"Incident date: {c['incident_date'] or 'not recorded'}",
                f"Location: {c['location'] or 'not recorded'}",
                "Investigators: " + (", ".join(f"{t['full_name']} ({t['permission_level']})" for t in bundle["team"])
                                     or "none assigned"),
                f"Records: {len(bundle['suspects'])} suspects, {len(bundle['witnesses'])} witnesses, "
                f"{len(bundle['evidence'])} evidence items, {len(bundle['timeline'])} timeline events",
            ]),
            section("Case description (recorded)", [c["description"] or "No description recorded."]),
        ],
        "references": [_case_ref(c)],
        "context": llm_case_context(bundle, ("case",)),
    }


def handle_summary(user, question, allowed, case_numbers):
    bundle, error = _need_case(case_numbers, allowed)
    if error:
        return error
    return {
        "sections": [section("Automated summary from stored records (not AI)",
                             deterministic_summary(bundle).split("\n"))],
        "references": [_case_ref(bundle["case"]),
                       {"label": "Reports & findings", "url": url_for("cases.view_case",
                        case_number=bundle["case"]["case_number"], tab="reports")}],
        "context": llm_case_context(bundle),
    }


def handle_timeline(user, question, allowed, case_numbers):
    bundle, error = _need_case(case_numbers, allowed)
    if error:
        return error
    events = bundle["timeline"]          # already merge-sorted by forensics.timeline
    items = [f"{e['time']}  |  {e['type']}  |  {e['description']}  (source: {e['source']})" for e in events]
    return {
        "sections": [section(f"Recorded timeline, merge-sorted ({len(events)} events)",
                             items or ["No timeline events recorded."])],
        "references": [{"label": "Open timeline", "url": url_for("cases.view_case",
                        case_number=bundle["case"]["case_number"], tab="timeline")}],
        "context": llm_case_context(bundle, ("case", "timeline", "witnesses", "evidence")),
    }


def handle_evidence(user, question, allowed, case_numbers):
    if not case_numbers:
        rows = evidence_for_cases(allowed)
        items = [f"{e['evidence_code']} [{e['case_number']}] {e['filename']} ({e['file_type']}) - "
                 f"{e['integrity_status']}" for e in rows]
        return {"sections": [section(f"Evidence across your {len(allowed)} accessible case(s)",
                                     items or ["No evidence recorded."])]}
    bundle, error = _need_case(case_numbers, allowed)
    if error:
        return error
    items = [f"{e['evidence_code']}  {e['filename']}  ({e['file_type']}, {e['file_size']:,} bytes) - integrity: "
             f"{e['integrity_status']} - {e['description'] or 'no description'}" for e in bundle["evidence"]]
    refs = [{"label": e["evidence_code"], "url": url_for("evidence.view", evidence_id=e["id"])}
            for e in bundle["evidence"]]
    return {
        "sections": [section(f"Evidence registered in {bundle['case']['case_number']}",
                             items or ["No evidence registered."])],
        "references": refs,
        "context": llm_case_context(bundle, ("case", "evidence", "relationships")),
    }


def handle_integrity_failures(user, question, allowed, case_numbers):
    ids = allowed
    if case_numbers:
        bundle, error = _need_case(case_numbers, allowed)
        if error:
            return error
        ids = [bundle["case"]["id"]]
    rows = evidence_for_cases(ids)
    failed = [e for e in rows if e["integrity_status"] in ("MISMATCH", "FILE MISSING")]
    unverified = [e for e in rows if e["integrity_status"] == "UNVERIFIED"]
    items = [f"{e['evidence_code']} [{e['case_number']}] {e['filename']}: {e['integrity_status']} "
             f"(last checked {e['last_verified_at']})" for e in failed]
    return {
        "sections": [
            section("Evidence that failed its latest integrity check",
                    items or [f"None. All verified evidence in {len(ids)} case(s) matched its original SHA-256."]),
            section("Not yet verified", [f"{e['evidence_code']} [{e['case_number']}] {e['filename']}"
                                         for e in unverified] or ["Every item has been verified at least once."]),
            section("Note", ["A MISMATCH means the stored file no longer matches its registered fingerprint. "
                             "It does not show who changed it or why."], "notice"),
        ],
        "references": [{"label": e["evidence_code"], "url": url_for("evidence.view", evidence_id=e["id"])}
                       for e in failed],
    }


def handle_suspect_evidence(user, question, allowed, case_numbers):
    ids = allowed
    if case_numbers:
        case = get_case_by_number(case_numbers[0])
        ids = [case["id"]] if case and case["id"] in allowed else []
    suspects = find_suspects(question, ids)
    if not suspects:
        return {"sections": [section("Suspect not found", [
            "No suspect in your accessible cases matches that name. Try the full name or the S-### code."], "notice")]}
    sections, refs, context = [], [], {"suspects": []}
    for s in suspects[:5]:
        linked = suspect_linked_evidence(s["id"])
        sections.append(section(f"{suspect_code(s['id'])} {s['name']} [{s['case_number']}]", [
            f"{l['evidence']['evidence_code']} {l['evidence']['filename']} - {l['relationship_type']}: {l['description']}"
            for l in linked] or ["No evidence is explicitly linked to this suspect."]))
        refs.append({"label": f"Dossier {suspect_code(s['id'])}", "url": url_for("cases.suspect_dossier",
                                                                                 suspect_id=s["id"])})
        context["suspects"].append({
            "id": suspect_code(s["id"]), "name": s["name"], "case": s["case_number"], "alibi": s["alibi"],
            "linked_evidence": [{"id": l["evidence"]["evidence_code"], "file": l["evidence"]["filename"],
                                 "link_type": l["relationship_type"], "basis": l["description"],
                                 "integrity": l["evidence"]["integrity_status"]} for l in linked]})
    return {"sections": sections, "references": refs, "context": context}


def handle_detective_cases(user, question, allowed, case_numbers):
    detective = find_detective(question)
    if detective is None and not is_admin(user):
        detective = user
    if detective is None:
        cases = list_cases(allowed)
        return {"sections": [section("All cases", [f"{c['case_number']} {c['title']} - {c['status']} - lead: "
                                                    f"{c['lead_name'] or 'unassigned'}" for c in cases])],
                "references": [_case_ref(c) for c in cases]}
    rows = cases_for_user_with_role(detective["id"])
    visible = [c for c in rows if c["id"] in allowed]
    hidden = len(rows) - len(visible)
    items = [f"{c['case_number']} {c['title']} - {c['status']} - role: {c['my_role']}" for c in visible]
    sections = [section(f"Cases for {detective['full_name']} ({detective['badge_id']})",
                        items or ["No cases visible to you."])]
    if hidden:
        sections.append(section("Access restriction", [
            f"{hidden} other case(s) are assigned to this detective but are not shared with you."], "notice"))
    return {"sections": sections, "references": [_case_ref(c) for c in visible]}


def handle_witnesses(user, question, allowed, case_numbers):
    bundle, error = _need_case(case_numbers, allowed)
    if error:
        return error
    items = [f"{w['code']} {w['name']} (recorded {w['recorded_at']}): \"{w['statement']}\"" for w in bundle["witnesses"]]
    return {"sections": [section(f"Witness statements in {bundle['case']['case_number']}",
                                 items or ["No witness statements recorded."])],
            "references": [{"label": "Witnesses tab", "url": url_for("cases.view_case",
                            case_number=bundle["case"]["case_number"], tab="witnesses")}],
            "context": llm_case_context(bundle, ("case", "witnesses", "suspects"))}


def handle_suspects(user, question, allowed, case_numbers):
    bundle, error = _need_case(case_numbers, allowed)
    if error:
        return error
    items = [f"{s['code']} {s['name']} - {s['relationship'] or 'relationship not recorded'}. "
             f"Alibi: {s['alibi'] or 'not recorded'}" for s in bundle["suspects"]]
    return {"sections": [section(f"Suspects in {bundle['case']['case_number']}", items or ["No suspects recorded."])],
            "references": [{"label": f"Dossier {s['code']}", "url": url_for("cases.suspect_dossier", suspect_id=s["id"])}
                           for s in bundle["suspects"]],
            "context": llm_case_context(bundle, ("case", "suspects", "witnesses"))}


def handle_report(user, question, allowed, case_numbers):
    from reports.generator import create_case_report      # local import keeps module start-up light
    bundle, error = _need_case(case_numbers, allowed)
    if error:
        return error
    report_id, summary_source = create_case_report(bundle["case"]["id"], user, use_ai=True)
    return {
        "sections": [section("Investigation report generated", [
            f"Case {bundle['case']['case_number']} report saved as PDF.",
            "Summary source: " + ("AI-generated (clearly labelled inside the report)"
                                  if summary_source.startswith("ai") else "deterministic summary from stored records"),
            "The report lists recorded information only and does not determine guilt."])],
        "references": [{"label": "Download PDF report", "url": url_for("reports.download", report_id=report_id)}],
    }


def handle_search(user, question, allowed, case_numbers):
    from routes.detectives import run_search
    results, notes = run_search(user, question)
    sections = []
    labels = {"cases": "Cases", "suspects": "Suspects", "witnesses": "Witness statements",
              "evidence": "Evidence", "notes": "Investigator notes"}
    for key, heading in labels.items():
        rows = results.get(key, [])[:6]
        if rows:
            sections.append(section(heading, [
                f"[{r.get('case_number', '')}] " + (r.get("title") or r.get("name") or r.get("filename") or "")
                + (f" - {r.get('evidence_code')}" if r.get("evidence_code") else "") for r in rows]))
    if not sections:
        sections.append(section("No matches", [
            "Nothing in your accessible cases matched. Try: \"Summarize Case 001\", "
            "\"What evidence is available in Case 002?\", \"Explain the timeline of Case 001\"."], "notice"))
    sections.append(section("How this was searched", notes, "notice"))
    context = {"search_results": {k: [dict(r) for r in v[:6]] for k, v in results.items() if k != "exact"}}
    return {"sections": sections, "references": [{"label": r["label"], "url": r["url"]} for r in results["exact"]],
            "context": context if any(results[k] for k in labels) else None}


HANDLERS = {
    "show_case": handle_show_case,
    "summary": handle_summary,
    "timeline": handle_timeline,
    "evidence": handle_evidence,
    "integrity_failures": handle_integrity_failures,
    "suspect_evidence": handle_suspect_evidence,
    "detective_cases": handle_detective_cases,
    "witnesses": handle_witnesses,
    "suspects": handle_suspects,
    "report": handle_report,
    "search": handle_search,
}
